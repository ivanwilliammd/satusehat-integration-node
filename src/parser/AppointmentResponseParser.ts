/**
 * AppointmentResponseParser — pembaca elemen tingkat atas resource FHIR R4 AppointmentResponse.
 *
 * Dihasilkan dari AppointmentResponseBuilder oleh scripts/generate_parsers.py — jangan disunting tangan.
 * Setiap getter mengembalikan null bila elemen tidak ada, sehingga pemanggil tidak pernah
 * terhenti oleh akses yang meleset.
 */
export class AppointmentResponseParser {
  private payload: Record<string, any>;

  constructor(payload: Record<string, any> = {}) {
    this.payload = payload ?? {};
  }

  getRaw(): Record<string, any> {
    return this.payload;
  }

  getId(): any {
    return this.payload['id'] ?? null;
  }

  getAppointment(): any {
    return this.payload['appointment'] ?? null;
  }

  getParticipantStatus(): any {
    return this.payload['participantStatus'] ?? null;
  }

  getActor(): any {
    return this.payload['actor'] ?? null;
  }

  getIdentifier(): any {
    return this.payload['identifier'] ?? null;
  }

  getStatus(): any {
    return this.payload['status'] ?? null;
  }

  getCode(): any {
    return this.payload['code'] ?? null;
  }

  getSubject(): any {
    return this.payload['subject'] ?? null;
  }

  getEncounter(): any {
    return this.payload['encounter'] ?? null;
  }
}
